package kz.kaspi.models.enums;

/**
 * Статус распределения начисления бонусов при проверке месячного лимита (30 000 бонусов).
 */
public enum SplitStatus {
    /**
     * Бонусы начислены в полном объеме (лимит не превышен).
     */
    FULL_AWARDED,

    /**
     * Транзакция разбита (Split): часть суммы получила акционные бонусы до достижения лимита,
     * а превышающая часть рассчитана по ставке 0%.
     */
    SPLIT_TRANSACTION,

    /**
     * Месячный лимит (30 000 бонусов) уже был полностью исчерпан до этой транзакции.
     * Начислено 0 бонусов.
     */
    LIMIT_REACHED_ZERO_BONUS,

    /**
     * По данной транзакции нет активных акций/промо (бонусы не начисляются).
     */
    NO_PROMO;

    /**
     * Проверяет, начислялись ли бонусы по операции (полностью или частично со сплитом).
     */
    public boolean hasBonuses() {
        return this == FULL_AWARDED || this == SPLIT_TRANSACTION;
    }

    /**
     * Проверяет, затронул ли расчет лимит бонусов (частично разбита или лимит уже был исчерпан).
     */
    public boolean isLimitImpacted() {
        return this == SPLIT_TRANSACTION || this == LIMIT_REACHED_ZERO_BONUS;
    }
}
